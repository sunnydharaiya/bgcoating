const fs = require('fs');
const path = require('path');
function walk(dir) {
    let results = [];
    const list = fs.readdirSync(dir);
    list.forEach(file => {
        file = path.join(dir, file);
        if (fs.statSync(file).isDirectory()) results = results.concat(walk(file));
        else if (file.endsWith('.jsx')) results.push(file);
    });
    return results;
}
const files = walk(path.join(__dirname, 'src', 'tools'));

files.forEach(file => {
    let content = fs.readFileSync(file, 'utf8');
    let original = content;

    // 1. Remove the orange badge and relative border wrapper that I injected!
    content = content.replace(/<div className="relative border-2 border-\[\#F7941D\]\/30 rounded-xl p-5 md:p-6 pt-7 md:pt-8 mt-4">\s*<div className="absolute -top-3 left-4 md:left-6 bg-gradient-to-r from-\[\#FBA435\] to-\[\#F7941D\] text-white text-\[9px\] md:text-\[10px\] font-bold px-3 py-1\.5 rounded-sm uppercase tracking-wider flex items-center gap-1\.5 shadow-sm">\s*<BookOpen className="w-3 h-3" \/>\s*USER INPUTS — PLEASE FILL CORRECTLY\s*<\/div>\s*<div className="grid grid-cols-1 sm:grid-cols-2 gap-4 gap-y-5">/g, 
        '<div className="grid grid-cols-1 sm:grid-cols-2 gap-4 gap-y-5">');

    // 2. Change the layout from split to vertical
    content = content.replace(/className="grid grid-cols-1 lg:grid-cols-12 gap-6"/g, 'className="flex flex-col gap-6"');
    content = content.replace(/className="grid grid-cols-1 xl:grid-cols-12 gap-6"/g, 'className="flex flex-col gap-6"');
    
    content = content.replace(/className="lg:col-span-[0-9]+/g, 'className="w-full');
    content = content.replace(/className="xl:col-span-[0-9]+/g, 'className="w-full');

    // 3. Change labels to orange uppercase
    content = content.replace(/className="block text-xs font-bold text-slate-700( mb-1\.5)?"/g, 'className="block text-[10px] md:text-xs font-bold text-[#F7941D] uppercase tracking-wider mb-1.5"');
    content = content.replace(/className="block text-sm font-bold text-slate-700( mb-1\.5)?"/g, 'className="block text-[10px] md:text-xs font-bold text-[#F7941D] uppercase tracking-wider mb-1.5"');

    // 4. Wrap Results Output Section in the Green Badge
    if (content.includes('{/* Results Output Section */}') && !content.includes('CALCULATED RESULT — GENERATED BY SYSTEM')) {
        content = content.replace(
            /{\/\* Results Output Section \*\/}/,
            `{/* Results Output Section */}
        <div className="relative border-2 border-emerald-500/30 rounded-xl p-5 md:p-6 pt-8 mt-6 bg-emerald-50/10">
          <div className="absolute -top-3 left-4 md:left-6 bg-[#10B981] text-white text-[9px] md:text-[10px] font-bold px-3 py-1.5 rounded-sm uppercase tracking-wider flex items-center gap-1.5 shadow-sm">
            <Check className="w-3 h-3" />
            CALCULATED RESULT — GENERATED BY SYSTEM
          </div>`
        );
    }
    
    // 5. Restore Solid Orange Calculate button (remove the gradient)
    content = content.replace(
        /bg-gradient-to-r from-\[\#FBA435\] to-\[\#F7941D\] hover:from-\[\#F7941D\] hover:to-\[\#E8700A\] text-white/g,
        'bg-[#F7941D] hover:bg-[#E8700A] text-white'
    );
    
    // We must balance divs at the end of the file!
    // Since we removed one div at the start and potentially added one at Results Output,
    // we need a general div balancer like before.
    let opens = (content.match(/<div(?:\s|>)/g) || []).length;
    let closes = (content.match(/<\/div>/g) || []).length;
    
    if (opens !== closes) {
        let diff = opens - closes;
        if (diff > 0) {
            let divs = '\n' + '</div>\n'.repeat(diff);
            let lastIndex = content.lastIndexOf('  );\n}');
            if (lastIndex !== -1) {
                content = content.substring(0, lastIndex) + divs + content.substring(lastIndex);
            } else {
                let backupIndex = content.lastIndexOf(');');
                if (backupIndex !== -1) {
                    content = content.substring(0, backupIndex) + divs + content.substring(backupIndex);
                }
            }
        } else if (diff < 0) {
            // we have TOO MANY closes! This means we removed an opening tag but didn't remove its closing tag.
            // Let's just remove the extra closing tags from the bottom.
            // We just strip `</div>\n` a few times from the end of the component.
            let toRemove = -diff;
            for (let i = 0; i < toRemove; i++) {
                content = content.replace(/\n\s*<\/div>\s*(\n\s*\);\n?\}?[\s\S]*)$/, '$1');
            }
        }
    }

    if (content !== original) {
        fs.writeFileSync(file, content, 'utf8');
        console.log('Processed: ' + file);
    }
});
